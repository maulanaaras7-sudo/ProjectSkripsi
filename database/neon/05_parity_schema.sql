-- Apply once to an existing Neon database created before the PHP-parity work.
-- Uses only additive, idempotent DDL; run with DATABASE_URL_UNPOOLED.

BEGIN;

CREATE TABLE IF NOT EXISTS contoh_soal (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_contoh VARCHAR(50) NOT NULL UNIQUE,
  tingkat VARCHAR(10) NOT NULL CHECK (tingkat IN ('rendah','sedang','tinggi')),
  urutan INTEGER NOT NULL CHECK (urutan > 0),
  sub_materi VARCHAR(120) NOT NULL,
  capaian_pembelajaran TEXT NOT NULL,
  tujuan_pembelajaran TEXT NOT NULL,
  pertanyaan TEXT NOT NULL,
  pilihan_a VARCHAR(255) NOT NULL, pilihan_b VARCHAR(255) NOT NULL,
  pilihan_c VARCHAR(255) NOT NULL, pilihan_d VARCHAR(255) NOT NULL, pilihan_e VARCHAR(255),
  jawaban_benar VARCHAR(1) NOT NULL CHECK (jawaban_benar IN ('a','b','c','d','e')),
  hint_1 TEXT NOT NULL, hint_2 TEXT NOT NULL, pembahasan TEXT NOT NULL,
  feedback_salah JSONB NOT NULL DEFAULT '{}'::jsonb, metadata_verifikasi JSONB,
  aktif SMALLINT NOT NULL DEFAULT 1 CHECK (aktif IN (0,1)),
  UNIQUE(tingkat,urutan)
);
CREATE INDEX IF NOT EXISTS idx_contoh_soal_bank ON contoh_soal(tingkat,aktif,urutan);

CREATE TABLE IF NOT EXISTS progres_contoh_soal (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  contoh_soal_id INTEGER NOT NULL REFERENCES contoh_soal(id) ON DELETE CASCADE,
  jawaban_terakhir VARCHAR(1) CHECK (jawaban_terakhir IN ('a','b','c','d','e')),
  jumlah_percobaan INTEGER NOT NULL DEFAULT 0 CHECK (jumlah_percobaan >= 0),
  pernah_benar SMALLINT NOT NULL DEFAULT 0 CHECK (pernah_benar IN (0,1)),
  pertama_dikerjakan_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  terakhir_dikerjakan_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(user_id,contoh_soal_id)
);

CREATE TABLE IF NOT EXISTS draft_jawaban_evaluasi (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  attempt_key VARCHAR(191) NOT NULL, jenis VARCHAR(10) NOT NULL CHECK (jenis IN ('pretest','posttest')),
  soal_id INTEGER NOT NULL REFERENCES soal(id) ON DELETE CASCADE,
  jawaban_dipilih VARCHAR(1) NOT NULL CHECK (jawaban_dipilih IN ('a','b','c','d','e')),
  diperbarui_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(user_id,attempt_key,soal_id)
);
CREATE INDEX IF NOT EXISTS idx_draft_evaluasi_user_jenis ON draft_jawaban_evaluasi(user_id,jenis);

CREATE TABLE IF NOT EXISTS evaluation_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  jenis VARCHAR(10) NOT NULL CHECK (jenis IN ('pretest','posttest')),
  dimulai_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deadline_pada TIMESTAMPTZ NOT NULL,
  UNIQUE(user_id,jenis)
);

COMMIT;
