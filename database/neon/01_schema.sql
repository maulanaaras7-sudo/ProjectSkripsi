-- Fungsiverse PostgreSQL schema for Neon.
-- Run this file first in the Neon SQL Editor.

BEGIN;

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(10) NOT NULL DEFAULT 'siswa' CHECK (role IN ('guru','siswa')),
  kelompok VARCHAR(10) CHECK (kelompok IN ('rendah','sedang','tinggi')),
  pretest_selesai SMALLINT NOT NULL DEFAULT 0 CHECK (pretest_selesai IN (0,1)),
  posttest_selesai SMALLINT NOT NULL DEFAULT 0 CHECK (posttest_selesai IN (0,1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS materi (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  judul VARCHAR(150) NOT NULL UNIQUE,
  urutan INTEGER NOT NULL DEFAULT 0,
  konten TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS soal (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_soal VARCHAR(50) UNIQUE,
  materi_id INTEGER REFERENCES materi(id) ON DELETE SET NULL,
  jenis VARCHAR(10) NOT NULL DEFAULT 'latihan' CHECK (jenis IN ('pretest','latihan','posttest')),
  tingkat_kesulitan VARCHAR(10) NOT NULL DEFAULT 'sedang' CHECK (tingkat_kesulitan IN ('rendah','sedang','tinggi')),
  sub_materi VARCHAR(120),
  capaian_pembelajaran TEXT,
  tujuan_pembelajaran TEXT,
  kode_tp VARCHAR(5),
  kode_ipk VARCHAR(8),
  level_kognitif VARCHAR(2) CHECK (level_kognitif IN ('C2','C3','C4')),
  pertanyaan TEXT NOT NULL,
  pilihan_a VARCHAR(255) NOT NULL,
  pilihan_b VARCHAR(255) NOT NULL,
  pilihan_c VARCHAR(255) NOT NULL,
  pilihan_d VARCHAR(255) NOT NULL,
  pilihan_e VARCHAR(255),
  jawaban_benar VARCHAR(1) NOT NULL CHECK (jawaban_benar IN ('a','b','c','d','e')),
  pembahasan TEXT,
  metadata_verifikasi JSONB,
  aktif SMALLINT NOT NULL DEFAULT 1 CHECK (aktif IN (0,1))
);
CREATE INDEX IF NOT EXISTS idx_soal_bank ON soal(jenis,aktif,tingkat_kesulitan,sub_materi);
CREATE INDEX IF NOT EXISTS idx_soal_tp_ipk ON soal(kode_tp,kode_ipk,level_kognitif);

CREATE TABLE IF NOT EXISTS jawaban_siswa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  soal_id INTEGER NOT NULL REFERENCES soal(id) ON DELETE CASCADE,
  jawaban_dipilih VARCHAR(1) NOT NULL CHECK (jawaban_dipilih IN ('a','b','c','d','e')),
  benar SMALLINT NOT NULL CHECK (benar IN (0,1)),
  waktu TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_jawaban_user_waktu ON jawaban_siswa(user_id,waktu);
CREATE INDEX IF NOT EXISTS idx_jawaban_user_soal ON jawaban_siswa(user_id,soal_id);

CREATE TABLE IF NOT EXISTS progres_latihan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  tingkat_awal VARCHAR(10) NOT NULL CHECK (tingkat_awal IN ('rendah','sedang','tinggi')),
  tingkat_saat_ini VARCHAR(10) CHECK (tingkat_saat_ini IN ('rendah','sedang','tinggi')),
  selesai_latihan SMALLINT NOT NULL DEFAULT 0 CHECK (selesai_latihan IN (0,1)),
  posttest_diizinkan SMALLINT NOT NULL DEFAULT 0 CHECK (posttest_diizinkan IN (0,1)),
  alasan_selesai VARCHAR(30) CHECK (alasan_selesai IN ('lulus_tingkat_tinggi','batas_sesi_habis','migrasi_data_lama')),
  dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  diperbarui_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  selesai_pada TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS progres_latihan_tingkat (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  tingkat VARCHAR(10) NOT NULL CHECK (tingkat IN ('rendah','sedang','tinggi')),
  jumlah_sesi INTEGER NOT NULL DEFAULT 0 CHECK (jumlah_sesi >= 0),
  status VARCHAR(25) NOT NULL DEFAULT 'belum_dimulai' CHECK (status IN ('belum_dimulai','berjalan','lulus','dilewati','batas_sesi_habis')),
  mulai_pada TIMESTAMPTZ,
  selesai_pada TIMESTAMPTZ,
  UNIQUE(user_id,tingkat)
);

CREATE TABLE IF NOT EXISTS riwayat_sesi_latihan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  tingkat VARCHAR(10) NOT NULL CHECK (tingkat IN ('rendah','sedang','tinggi')),
  nomor_sesi INTEGER NOT NULL CHECK (nomor_sesi > 0),
  jumlah_soal INTEGER NOT NULL CHECK (jumlah_soal > 0),
  jumlah_benar INTEGER,
  persentase NUMERIC(5,2),
  status VARCHAR(25) NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','ulang','naik_tingkat','selesai_latihan','batas_sesi_habis')),
  dimulai_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  dikumpulkan_pada TIMESTAMPTZ,
  UNIQUE(user_id,tingkat,nomor_sesi)
);
CREATE INDEX IF NOT EXISTS idx_sesi_user_status ON riwayat_sesi_latihan(user_id,status);

CREATE TABLE IF NOT EXISTS sesi_latihan_soal (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sesi_id BIGINT NOT NULL REFERENCES riwayat_sesi_latihan(id) ON DELETE CASCADE,
  soal_id INTEGER NOT NULL REFERENCES soal(id) ON DELETE RESTRICT,
  urutan INTEGER NOT NULL CHECK (urutan > 0),
  jawaban_dipilih VARCHAR(1) CHECK (jawaban_dipilih IN ('a','b','c','d','e')),
  benar SMALLINT CHECK (benar IN (0,1)),
  UNIQUE(sesi_id,soal_id),
  UNIQUE(sesi_id,urutan)
);

CREATE TABLE IF NOT EXISTS aktivitas_materi (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  materi_id INTEGER NOT NULL REFERENCES materi(id) ON DELETE CASCADE,
  judul VARCHAR(180) NOT NULL,
  deskripsi TEXT NOT NULL,
  soal_ringkas TEXT NOT NULL,
  aktif SMALLINT NOT NULL DEFAULT 1 CHECK (aktif IN (0,1)),
  UNIQUE(materi_id,judul)
);

CREATE TABLE IF NOT EXISTS langkah_aktivitas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aktivitas_id INTEGER NOT NULL REFERENCES aktivitas_materi(id) ON DELETE CASCADE,
  urutan INTEGER NOT NULL,
  pertanyaan TEXT NOT NULL,
  pilihan TEXT NOT NULL,
  jawaban_benar VARCHAR(100) NOT NULL,
  feedback_benar TEXT NOT NULL,
  feedback_salah TEXT NOT NULL,
  petunjuk TEXT NOT NULL,
  UNIQUE(aktivitas_id,urutan)
);

CREATE TABLE IF NOT EXISTS progres_aktivitas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  langkah_id INTEGER NOT NULL REFERENCES langkah_aktivitas(id) ON DELETE CASCADE,
  jawaban_terakhir VARCHAR(100),
  jumlah_percobaan INTEGER NOT NULL DEFAULT 0,
  selesai SMALLINT NOT NULL DEFAULT 0 CHECK (selesai IN (0,1)),
  selesai_at TIMESTAMPTZ,
  UNIQUE(user_id,langkah_id)
);

